# -*- coding: utf-8 -*-
"""규격 3.2 한글 발음 규칙의 결정성 검증기.
ruby 컬럼 -> romaji_ko 를 기계 생성해서 사람이 적은 값과 대조한다.

핵심: 촉음(っ)·발음(ん)은 **루비 경계를 넘어** 다음 글자를 봐야 하고,
      장음은 **조각 경계를 넘지 않는다**. 스코프가 서로 다르므로
      가나 전체를 한 줄로 펴 놓고 글자마다 조각 번호를 달아 1패스로 처리한다.

🔴 2026-07-23 개정 (N5 단어 400건 작업 중 발견)
  ① 장음 스코프 = "루비 안" 이 아니라 **조각(= 루비 그룹 1개 또는 순가나 런 1개)**.
     구판은 루비 밖 가나에 장음을 아예 적용하지 않아 한자 없는 단어가 전부 틀렸다
     (どうぞ→'도우조', ありがとう→'아리가토우'). N3 파일럿은 전 항목이 한자어라
     이 결함이 드러나지 않았다.
     조각 단위로 바꿔도 `{思|おも}う`(오모우)는 그대로다 — おも와 う가 다른 조각이므로.
  ② 어말 は가 조사에서 굳은 단어(こんにちは·こんばんは)는 **어휘 단위 예외**.
     "어말 は→わ"를 규칙으로 두면 はは(母)가 '하와'가 되므로 규칙화 불가.
"""
import io, re, csv, sys

BASE = {
 'あ':'아','い':'이','う':'우','え':'에','お':'오',
 'か':'카','き':'키','く':'쿠','け':'케','こ':'코',
 'が':'가','ぎ':'기','ぐ':'구','げ':'게','ご':'고',
 'さ':'사','し':'시','す':'스','せ':'세','そ':'소',
 'ざ':'자','じ':'지','ず':'즈','ぜ':'제','ぞ':'조',
 'た':'타','ち':'치','つ':'츠','て':'테','と':'토',
 'だ':'다','ぢ':'지','づ':'즈','で':'데','ど':'도',
 'な':'나','に':'니','ぬ':'누','ね':'네','の':'노',
 'は':'하','ひ':'히','ふ':'후','へ':'헤','ほ':'호',
 'ば':'바','び':'비','ぶ':'부','べ':'베','ぼ':'보',
 'ぱ':'파','ぴ':'피','ぷ':'푸','ぺ':'페','ぽ':'포',
 'ま':'마','み':'미','む':'무','め':'메','も':'모',
 'や':'야','ゆ':'유','よ':'요',
 'ら':'라','り':'리','る':'루','れ':'레','ろ':'로',
 'わ':'와','を':'오',
}
YOUON = {
 'きゃ':'캬','きゅ':'큐','きょ':'쿄','ぎゃ':'갸','ぎゅ':'규','ぎょ':'교',
 'しゃ':'샤','しゅ':'슈','しょ':'쇼','じゃ':'자','じゅ':'주','じょ':'조',
 'ちゃ':'차','ちゅ':'추','ちょ':'초','にゃ':'냐','にゅ':'뉴','にょ':'뇨',
 'ひゃ':'햐','ひゅ':'휴','ひょ':'효','びゃ':'뱌','びゅ':'뷰','びょ':'뵤',
 'ぴゃ':'퍄','ぴゅ':'퓨','ぴょ':'표','みゃ':'먀','みゅ':'뮤','みょ':'묘',
 'りゃ':'랴','りゅ':'류','りょ':'료',
}
ROW = {}
for ks, v in [('かきくけこがぎぐげご','k'), ('さしすせそざじずぜぞ','s'),
              ('たちつてとだぢづでど','t'), ('なにぬねの','n'),
              ('はひふへほ','h'), ('ばびぶべぼ','b'), ('ぱぴぷぺぽ','p'),
              ('まみむめも','m'), ('やゆよ','y'), ('らりるれろ','r'),
              ('わを','w'), ('あいうえお','v')]:
    for k in ks: ROW[k] = v

JUNG = list('ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ')
JONG = [''] + list('ㄱㄲㄳㄴㄵㄶㄷㄹㄺㄻㄼㄽㄾㄿㅀㅁㅂㅄㅅㅆㅇㅈㅊㅋㅌㅍㅎ')
# 'ㅡ'는 す·ず·つ(스·즈·츠)의 모음이다. 일본어 모음으로는 /u/ 이므로 '우'로 반복한다.
# (2026-07-23 추가 — 없으면 スーパー 같은 「ー」 단어에서 조용히 빈 글자가 섞였다)
VOWEL_OF = {'ㅏ':'아','ㅣ':'이','ㅜ':'우','ㅔ':'에','ㅗ':'오','ㅑ':'아','ㅠ':'우','ㅛ':'오',
            'ㅡ':'우','ㅘ':'아'}                       # ㅘ = わ(/wa/)
LONG_PAIR = {('오','う'), ('오','お'), ('에','い'), ('에','え'),
             ('우','う'), ('이','い'), ('아','あ')}
KATA2HIRA = {chr(c): chr(c - 0x60) for c in range(0x30A1, 0x30F7)}

def decomp(ch):
    c = ord(ch) - 0xAC00
    return c // 588, (c % 588) // 28, c % 28

def add_batchim(syl, jong):
    i, j, _ = decomp(syl)
    return chr(0xAC00 + i*588 + j*28 + JONG.index(jong))

def vowel_char(syl):
    """앞 음절의 모음 글자. 모르는 모음이면 조용히 넘기지 않고 터뜨린다."""
    _, j, _ = decomp(syl)
    if JUNG[j] not in VOWEL_OF:
        raise ValueError('모음 대응 없음: %r (%s)' % (syl, JUNG[j]))
    return VOWEL_OF[JUNG[j]]

TOKEN = re.compile(r'\{([^|{}]+)((?:\|[^|{}]*)+)\}')

# 어휘 단위 예외 (규격 3.2.6) — 조사 は가 어휘 안에서 굳은 것. 규칙화하면 はは(母)가 깨진다.
#
# 🔴 2026-07-23 2차 개정 (N4 단어 400건 작업 중 발견)
#   flatten()의 조사 예외는 "순가나 런 전체가 정확히 'は'/'へ'일 때"만 발동한다.
#   그래서 {実|じつ}は(는 런이 'は' 하나라) 통과하지만, それでは·または처럼
#   **다른 가나 뒤에 조사 は가 붙은 한 덩어리**는 잡지 못하고 '소레데하'로 조용히 틀린다.
#   런 안을 스캔해서 고치는 방식은 못 쓴다 — はは(母)·はは행 어휘가 전부 깨진다.
#   조사인지 아닌지는 형태소 정보이지 표기 정보가 아니므로, **어휘 단위 예외가 유일한 해법**이다.
WORD_EXCEPTIONS = {
    # (1) 조사 は → わ. 어휘 안에 섞여 있어 3.2.6 규칙만으로는 못 잡는 것들.
    'こんにちは': 'こんにちわ',
    'こんばんは': 'こんばんわ',
    'それでは':   'それでわ',
    'では':       'でわ',
    'または':     'またわ',
    # (2) 🔴 순가나 복합어의 형태소 경계 (2026-07-23 추가).
    #     장음 판정은 "같은 조각 안에서만" 성립하는데(3.2.5-1), 조각 경계는 **루비 브래킷**으로만 생긴다.
    #     한자가 없는 복합어는 경계를 표시할 방법이 없어, の+う 가 장음으로 잘못 붙는다.
    #     → 브래킷을 넣어 조각을 강제로 나눈다. (읽기는 표기와 동일하게 두면 루비가 생기지 않는다)
    #     예: そのうえ = その + うえ(上) → 소노「우」에 (소노「오」에 ✕)
    'そのうえ':   'その{うえ|うえ}',
}

def flatten(ruby):
    """ruby 문자열 -> [(글자, 조각번호)] 평면 스트림. 조사 は/へ는 미리 치환.

    조각번호: 루비 그룹 하나 = 조각 하나, 연속된 순가나 런 = 조각 하나.
    장음은 같은 조각 안에서만 성립한다(규격 3.2.5-1).
    """
    out, pos, seg = [], 0, [0]
    def push_plain(s):
        if not s: return
        seg[0] += 1
        if s in ('は', 'へ'):                        # 조사 예외 (규격 3.2.6)
            out.append((('わ' if s == 'は' else 'え'), seg[0]))
            return
        for c in s: out.append((c, seg[0]))
    for m in TOKEN.finditer(ruby):
        push_plain(ruby[pos:m.start()])
        seg[0] += 1
        for c in ''.join(m.group(2).split('|')[1:]): out.append((c, seg[0]))
        pos = m.end()
    push_plain(ruby[pos:])
    return out

def ruby_to_ko(ruby):
    st = flatten(WORD_EXCEPTIONS.get(ruby, ruby))
    hira = [(KATA2HIRA.get(c, c), sg, c) for c, sg in st]
    out, i, n = [], 0, len(hira)
    while i < n:
        h, sg, raw = hira[i]
        lg = (i > 0 and hira[i-1][1] == sg)          # 앞 글자와 같은 조각일 때만 장음 후보
        nxt = hira[i+1][0] if i+1 < n else ''
        if raw in ('ー', 'ｰ'):                                   # 가타카나 장음부호
            out.append(vowel_char(out[-1]) if out else ''); i += 1; continue
        if h + nxt in YOUON:
            out.append(YOUON[h + nxt]); i += 2; continue
        if h == 'っ':                                            # 촉음 — 경계를 넘어 lookahead
            jong = {'k':'ㄱ','s':'ㅅ','t':'ㅅ','p':'ㅂ'}.get(ROW.get(nxt, ''), '')
            if jong and out: out[-1] = add_batchim(out[-1], jong)
            i += 1; continue
        if h == 'ん':                                            # 발음 — 경계를 넘어 lookahead
            jong = {'m':'ㅁ','b':'ㅁ','p':'ㅁ','k':'ㅇ'}.get(ROW.get(nxt, ''), 'ㄴ')
            if out: out[-1] = add_batchim(out[-1], jong)
            i += 1; continue
        if lg and out and (vowel_char(out[-1]), h) in LONG_PAIR:  # 장음 — 경계를 넘지 않음
            out.append(vowel_char(out[-1])); i += 1; continue
        if h in BASE:
            out.append(BASE[h]); i += 1; continue
        raise ValueError('unknown kana %r in %r' % (raw, ruby))
    return ''.join(out)

if __name__ == '__main__':
    rows = list(csv.reader(io.open(sys.argv[1], encoding='utf-8-sig')))
    bad = 0
    for r in rows[1:]:
        key, ruby, human = r[0], r[4], r[5]
        try:
            gen = ruby_to_ko(ruby)
        except Exception as e:
            print('ERR ', key, ruby, e); bad += 1; continue
        if gen != human:
            print('DIFF', key, ruby, '기계=' + gen, '사람=' + human); bad += 1
    print('총 %d건 / 불일치 %d건' % (len(rows) - 1, bad))
